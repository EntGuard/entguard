package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"unicode/utf8"
)

const sourceURL = "https://raw.githubusercontent.com/danielmiessler/SecLists/master/Passwords/Common-Credentials/100k-most-used-passwords-NCSC.txt"

// main generates passwords_generated.go file by downloading the necessary passwords from internet, normalize them and
// creates go file with map containing these passwords. The generated file also contains helper functions that couldn't
// be shared nicely/easily otherwise between generator and generated code usage places.
func main() {
	packageDir := packageDirectory() // calling it here to fail fast before making costly internet download
	phase1Collection, phase2Collection := extractPasswordsFromInternet()
	generateGoFile(packageDir, phase1Collection, phase2Collection)
}

func packageDirectory() string {
	// dynamically getting this file full filename
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		fmt.Fprintln(os.Stderr, "unable to get current file(generator.go) trace")
		os.Exit(1)
	}
	return filepath.Dir(filename) // getting directory part of the full name
}

func extractPasswordsFromInternet() ([]string, []string) {
	fmt.Println("Downloading and processing password list...")
	resp, err := http.Get(sourceURL)
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to download password list: %v\n", err)
		os.Exit(1)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		fmt.Fprintf(os.Stderr, "failed to download list: status code %d\n", resp.StatusCode)
		os.Exit(1)
	}

	scanner := bufio.NewScanner(resp.Body)
	seen := make(map[string]struct{}) // uniqueness tracking map
	var phase1Collection []string     // Will hold the first 3000 unique passwords
	var phase2Collection []string     // Will hold up to 3000 unique passwords >= 15 chars (from #3001 onwards)

	for scanner.Scan() {
		normalized := normalize(scanner.Text())
		if normalized == "" || strings.HasPrefix(normalized, "#") {
			continue // Skip empty lines and comments
		}

		// Phase 1: collect first 3000 unique passwords
		if len(phase1Collection) < 3000 {
			if _, exists := seen[normalized]; !exists {
				seen[normalized] = struct{}{}
				phase1Collection = append(phase1Collection, normalized)
			}
			continue
		}

		// Phase 2: additionally collect 3000 unique and long passwords (>= 15 chars)
		if len(phase2Collection) < 3000 {
			if _, exists := seen[normalized]; !exists {
				// Use utf8.RuneCountInString to measure actual character count rather than raw bytes
				if utf8.RuneCountInString(normalized) >= 15 {
					seen[normalized] = struct{}{}
					phase2Collection = append(phase2Collection, normalized)
				}
			}
		} else {
			break // we have filled both lists up to 3,000 each. We can stop scanning.
		}
	}

	if err := scanner.Err(); err != nil {
		fmt.Fprintf(os.Stderr, "error reading stream: %v\n", err)
		os.Exit(1)
	}
	return phase1Collection, phase2Collection
}

func generateGoFile(packageDir string, phase1Collection []string, phase2Collection []string) {
	// write file header boilerplate code and imports
	var buf bytes.Buffer
	fmt.Fprintln(&buf, "package passwords")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "// Code generated by `go generate` triggered by `make redownload-common-passwords`; DO NOT EDIT.")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "import (")
	fmt.Fprintln(&buf, "\t\"strings\"") // used by 'normalize' function
	fmt.Fprintln(&buf, ")")
	fmt.Fprintln(&buf)

	// write Go map boilerplate
	fmt.Fprintln(&buf, "var commonPasswords = map[string]struct{}{")

	// Combine both lists into the same generated map structure
	for _, password := range phase1Collection {
		fmt.Fprintf(&buf, "\t%q: {},\n", password)
	}
	for _, password := range phase2Collection {
		fmt.Fprintf(&buf, "\t%q: {},\n", password)
	}

	fmt.Fprintln(&buf, "}")

	// write 'normalize' function
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "func normalize(password string) string {")
	fmt.Fprintln(&buf, "\treturn strings.TrimSpace(strings.ToLower(password))")
	fmt.Fprintln(&buf, "}")

	// format the buffer using Go's standard gofmt engine
	outputPath := filepath.Join(packageDir, "passwords_generated.go")
	formattedCode, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to format generated code: %v\n", err)
		fmt.Fprintf(os.Stderr, "writing the unformatted code to file... ")
		err = os.WriteFile(outputPath, buf.Bytes(), 0644)
		if err != nil {
			fmt.Fprintf(os.Stderr, "failed to write generated file: %v\n", err)
		} else {
			fmt.Fprintf(os.Stderr, "done\n")
		}
		os.Exit(1)
	}

	// save the perfectly formatted byte stream to disk
	if err := os.WriteFile(outputPath, formattedCode, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write generated file: %v\n", err)
		os.Exit(1)
	}

	fmt.Println("--------------------------------------------------")
	fmt.Printf("Successfully generated passwords_generated.go!\n")
	fmt.Printf("- Phase 1 (First 3000 unique): %d passwords\n", len(phase1Collection))
	fmt.Printf("- Phase 2 (Long passwords >= 15 chars, starting from #3001): %d passwords\n", len(phase2Collection))
	fmt.Printf("- Combined unique map entries: %d\n", len(phase1Collection)+len(phase2Collection))
	fmt.Println("--------------------------------------------------")
}

// normalize normalizes the password so that 2 logically same passwords are string-equal. We also use this to simplify
// lower/upper case handling and treating different upper/lower cases as one case.
func normalize(password string) string {
	return strings.TrimSpace(strings.ToLower(password))
}
